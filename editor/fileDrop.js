// ============================================================
// editor/fileDrop.js — Files dragged onto the window.
//
// The browser's own reaction (opening the image in place of the app,
// with no way back) is always prevented, except for text dropped into a
// text field (backend/desktop.py also keeps the window on the app).
// WebKitGTK may give a file drop as a uri-list of file:// paths with
// no files: those are imported by path. In the editor:
//   on a figure          its image is replaced
//   anywhere else        each image becomes a new figure, centred where
//                        it was dropped (on the canvas) or on the slide
//   a CSV / TSV / JSON   in the app: a panel asks for a table, a plot
//                        (wide or long format, optionally a choice to
//                        pick the columns) or a choice (ui/dataDrop.js);
//                        on a plot: a layer of it; on a table: that table
//                        takes the file's cells. Without its path (a
//                        browser): a table of its cells
// In the app, the backend knows each file's full path (backend/desktop.py):
// the figure is copied into figures/ and linked to the original, so a
// plot regenerated by a script updates on the slide. Without a path (a
// browser) the image data is saved instead.
// ============================================================

import { state, pyApi, activeElements, flashSaveIndicator, markDirty } from '../core/state.js';
import { renderEditor } from './editor.js';
import { placeholder } from '../ui/busy.js';
import { addImageFile, addImagePath, replaceFigureImage, replaceFigureImageData } from '../elements/figure/figure.js';
import { tablePropsFromCsv, parseCellsText, DEFAULT_CSV_ROWS } from '../elements/table/table.js';
import { openDataDrop, describeData, guessPlot, plotFrom } from '../ui/dataDrop.js';
import { linkDataFile } from '../core/plotData.js';
import { addLayer } from '../core/plotLayers.js';

/** A step of a drop, printed in the terminal when the app runs with --debug. */
function trace(message) {
    try {
        const api = pyApi();
        if (api && typeof api.debug_log === 'function') api.debug_log(message);
    } catch (e) { /* never in the way */ }
}

const IMAGE_RE = /\.(png|jpe?g|gif|webp|svg|pdf|eps|bmp|tiff?)$/i;
const TABLE_RE = /\.(csv|tsv)$/i;
const DATA_RE = /\.(csv|tsv|json)$/i;
const PATH_WAIT_MS = 600;

function hasFiles(e) {
    return Boolean(e.dataTransfer) && [...(e.dataTransfer.types || [])].includes('Files');
}

function isImage(file) {
    return file.type.startsWith('image/') || file.type === 'application/pdf' || IMAGE_RE.test(file.name || '');
}

/** The full paths of the dropped files, from the backend (it gets them a moment after the page). */
async function droppedPaths(files) {
    const api = pyApi();
    if (!api || typeof api.take_dropped_paths !== 'function') return [];
    const until = Date.now() + PATH_WAIT_MS;
    while (Date.now() < until) {
        const res = await api.take_dropped_paths();
        const paths = (res && res.paths) || [];
        if (paths.length) {
            // Same files, same order (matched by name when possible).
            return files.map((f, i) => paths.find(p => p.split(/[/\\]/).pop() === f.name) || paths[i] || '');
        }
        await new Promise(r => setTimeout(r, 50));
    }
    return [];
}

/** A client point as slide coordinates, or null outside the canvas. */
function slidePoint(clientX, clientY) {
    const canvas = document.getElementById('slide-canvas');
    if (!canvas) return null;
    const r = canvas.getBoundingClientRect();
    if (clientX < r.left || clientX > r.right || clientY < r.top || clientY > r.bottom) return null;
    return {
        x: (clientX - r.left) * (canvas.offsetWidth / (r.width || 1)),
        y: (clientY - r.top) * (canvas.offsetHeight / (r.height || 1)),
    };
}

/** Index (in the active elements) of the `type` element under the drop, or null. */
function elementUnder(target, type = 'figure') {
    const node = target && target.closest && target.closest('#slide-canvas [data-element-id]');
    if (!node) return null;
    const id = Number(node.dataset.elementId);
    const idx = activeElements().findIndex(el => el.id === id);
    return idx >= 0 && activeElements()[idx].type === type ? idx : null;
}

function editorActive() {
    const editor = document.getElementById('editor-view');
    return Boolean(editor && editor.classList.contains('active'));
}

/** file:// paths in the drop's uri-list (WebKitGTK may give these and no files). */
function uriListPaths(dt) {
    let list = '';
    try { list = dt.getData('text/uri-list') || ''; } catch (err) { list = ''; }
    return list.split(/\r?\n/).map(l => l.trim()).filter(l => l.startsWith('file://'))
        .map(l => { try { return decodeURIComponent(new URL(l).pathname); } catch (err) { return ''; } })
        .filter(Boolean);
}

function webAddress(dt) {
    let list = '';
    try { list = dt.getData('text/uri-list') || dt.getData('text/plain') || ''; } catch (err) { list = ''; }
    return /^https?:\/\//.test(list.trim());
}

/** Text dragged into a text field (or the source editor) is the field's own business. */
function textFieldDrop(e) {
    const t = e.target;
    const field = t && t.closest && t.closest('input, textarea, [contenteditable="true"], .CodeMirror');
    return Boolean(field) && !hasFiles(e);
}

const baseName = (p) => p.split(/[/\\]/).pop();

/**
 * What was dropped, as [{ name, file?, path? }]: the files (with their
 * full path when the backend knows it), or the file paths of the uri-list.
 */
async function droppedItems(dt) {
    const files = [...(dt.files || [])];
    const uris = uriListPaths(dt);
    if (files.length) {
        const paths = await droppedPaths(files);
        return files.map((file, i) => ({
            name: file.name, file,
            path: paths[i] || uris.find(u => baseName(u) === file.name) || '',
        }));
    }
    return uris.map(path => ({ name: baseName(path), path }));
}

const isImageItem = (it) => (it.file ? isImage(it.file) : IMAGE_RE.test(it.name));
const isTableItem = (it) => TABLE_RE.test(it.name || '');
const isDataItem = (it) => DATA_RE.test(it.name || '');

/**
 * Installs the window's drop handling. `insert(type, props)` adds an
 * element (editor.js insertElement).
 */
export function initFileDrop(insert) {
    // Whatever is dragged over the window (files or not: WebKitGTK does not
    // always say), the browser must not take it, or it opens the file in
    // place of the app.
    window.addEventListener('dragover', (e) => {
        if (textFieldDrop(e)) return;
        e.preventDefault();
        const ok = editorActive() || Boolean(activeZone());
        if (e.dataTransfer) e.dataTransfer.dropEffect = ok ? 'copy' : 'none';
        document.body.classList.toggle('file-drag-over', ok);
    });
    window.addEventListener('dragleave', (e) => {
        if (!e.relatedTarget) document.body.classList.remove('file-drag-over');
    });
    window.addEventListener('drop', async (e) => {
        document.body.classList.remove('file-drag-over');
        if (textFieldDrop(e)) return;
        e.preventDefault(); // never let the window open what was dropped
        const dt = e.dataTransfer;
        const zone = activeZone();
        trace(`page drop event: types ${[...(dt && dt.types) || []].join(',')}, ${dt && dt.files ? dt.files.length : 0} file(s)`);
        if (!dt || (!zone && !editorActive())) return;
        const items = await droppedItems(dt);
        trace(`page drop items: ${items.map(it => `${it.name}${it.path ? ' @ ' + it.path : ''}`).join('; ')}`);
        if (zone) {
            if (items.length) zone.onDrop(items);
            return;
        }
        if (!items.length) {
            if (webAddress(dt)) flashSaveIndicator('Images from a web page: copy the image and paste it with Ctrl+V');
            return;
        }
        await importDropped(items, insert, e.target, slidePoint(e.clientX, e.clientY), { x: e.clientX, y: e.clientY });
    });

    // In the app the backend sends the drop from GTK itself (the page may
    // get no files): paths and the drop point in page pixels.
    window.gluonNativeDrop = (paths, x, y) => {
        document.body.classList.remove('file-drag-over');
        if (!Array.isArray(paths) || !paths.length) return;
        trace(`native drop: ${paths.join('; ')} at ${Math.round(x)},${Math.round(y)}`);
        const items = paths.map(path => ({ name: baseName(path), path }));
        const zone = activeZone();
        if (zone) {
            zone.onDrop(items);
            return;
        }
        if (!editorActive()) return;
        importDropped(items, insert, document.elementFromPoint(x, y), slidePoint(x, y), { x, y });
    };
}

// ---------- Drop zones (e.g. the Import dialog) ----------

const zones = [];

/** While `isActive()`, files dropped on the window go to `onDrop(items)`
 *  ([{ name, path?, file? }]) instead of the slide. */
export function registerDropZone(isActive, onDrop) {
    zones.push({ isActive, onDrop });
}

function activeZone() {
    return zones.find(z => z.isActive()) || null;
}

// The same drop can arrive twice (page event and backend): once per file name.
const recentlyDropped = new Map();
const DUPLICATE_MS = 3000;

function alreadyDropped(name) {
    const now = Date.now();
    for (const [k, t] of recentlyDropped) if (now - t > DUPLICATE_MS) recentlyDropped.delete(k);
    if (recentlyDropped.has(name)) return true;
    recentlyDropped.set(name, now);
    return false;
}

/** Props for a table from a dropped CSV: linked by its path, or its cells. */
async function tableProps(it) {
    if (it.path) return tablePropsFromCsv(it.path);
    if (!it.file) return null;
    const all = parseCellsText(await it.file.text());
    if (!all.length) return null;
    const rows = all.slice(0, DEFAULT_CSV_ROWS);
    flashSaveIndicator(`Table added${all.length > rows.length ? `: the first ${rows.length} of ${all.length} rows` : ''} (its file path is unknown here, so it is not linked)`);
    const scale = state.slideWidth / 1920;
    return { rows, width: Math.round(Math.max(1000 * scale, rows[0].length * 200 * scale)), height: Math.round(rows.length * 28 * scale * 1.9) };
}

/** Adds the dropped CSV files as tables (or fills the table they were dropped on). */
async function importTables(tables, insert, target, at) {
    const onTable = elementUnder(target, 'table');
    for (const [i, it] of tables.entries()) {
        trace(`table from ${it.path || it.name}`);
        const props = await placeholder(at && { x: at.x + i * 40, y: at.y + i * 40 }, `Reading ${it.name}…`, tableProps(it), { width: 640, height: 260 });
        if (!props) continue;
        if (onTable !== null && i === 0) {
            const el = activeElements()[onTable];
            el.rows = props.rows;
            delete el.widths;
            if (props.data) el.data = props.data; else delete el.data;
            if (props._mtime) el._mtime = props._mtime;
            markDirty();
            renderEditor();
            continue;
        }
        // Centred on the drop point (kept on the slide), several fanned out.
        const w = props.width, h = props.height;
        const cx = at ? at.x + i * 40 : state.slideWidth / 2, cy = at ? at.y + i * 40 : state.slideHeight / 2;
        props.x = Math.round(Math.max(0, Math.min(state.slideWidth - w, cx - w / 2)));
        props.y = Math.round(Math.max(0, Math.min(state.slideHeight - h, cy - h / 2)));
        trace(`table: ${props.rows.length} rows, inserting at ${props.x},${props.y}`);
        insert('table', props);
        trace('table inserted');
    }
}

/** A CSV dropped on a plot: a layer of it (its first numeric column as x, the others as lines; a column of names repeating: a line per name). */
async function addDataLayer(el, it) {
    const api = pyApi();
    if (!state.projectFolder) { flashSaveIndicator('Save the project first: the file is copied into its folder'); return; }
    const res = await api.read_plot_data(state.projectFolder, it.path);
    if (!res || !res.success) { flashSaveIndicator(`Could not read ${it.name}${res && res.error ? `: ${res.error}` : ''}`); return; }
    const info = describeData(res);
    if (info.kind !== 'table') { flashSaveIndicator(`${it.name}: no columns of numbers to draw`); return; }
    const g = guessPlot(info);
    const link = await linkDataFile(it.path);
    if (!link || !link.success) { flashSaveIndicator((link && link.error) || 'Could not copy the file'); return; }
    const plot = plotFrom(info, { kind: 'line', format: g.format, group: g.group, x: g.x, y: g.y, ys: new Set(g.ys), barX: g.barX }, link.relative_path, link.original);
    el.code = addLayer(el.code, plot.code);
    markDirty();
    renderEditor();
    flashSaveIndicator(`${link.relative_path}: added to the plot ✓`);
}

/** Adds the dropped images (or replaces the figure they were dropped on), and CSV tables. */
async function importDropped(items, insertAny, target, at, client = null) {
    const fresh = items.filter(it => !alreadyDropped(it.name));
    trace(`importing ${fresh.length} new of ${items.length}`);
    if (!fresh.length) return;
    const insert = (props) => insertAny('figure', props);
    // data files known by their path, not dropped on a table: on a plot, a layer of it; else ask (ui/dataDrop.js)
    const canAsk = pyApi() && typeof pyApi().read_plot_data === 'function';
    const asked = canAsk && elementUnder(target, 'table') === null ? fresh.filter(it => isDataItem(it) && it.path) : [];
    const onPlot = elementUnder(target, 'plot');
    for (const [i, it] of asked.entries()) {
        const point = at ? { x: at.x + i * 40, y: at.y + i * 40 } : null;
        if (onPlot !== null && !/\.json$/i.test(it.name)) await addDataLayer(activeElements()[onPlot], it);
        else await openDataDrop(it, point, client, insertAny);
    }
    const tables = fresh.filter(it => isTableItem(it) && !asked.includes(it));
    if (tables.length) await importTables(tables, insertAny, target, at);
    if (asked.length && !tables.length && !fresh.some(isImageItem)) return;
    const images = fresh.filter(isImageItem);
    if (!images.length) {
        if (!tables.length) flashSaveIndicator('Only images (PNG, JPG, SVG, PDF…) and tables (CSV) can be dropped on a slide');
        return;
    }
    const onFigure = elementUnder(target);
    const canLink = (it) => it.path && state.projectFolder;
    try {
        if (onFigure !== null) {
            const it = images[0];
            if (canLink(it)) await replaceFigureImage(onFigure, it.path);
            else if (it.file) await replaceFigureImageData(onFigure, it.file);
            else throw new Error('save the project first');
            flashSaveIndicator('Figure replaced ✓');
            return;
        }
        for (const [i, it] of images.entries()) {
            // Several images: fanned out a little from the drop point.
            const point = at ? { x: at.x + i * 40, y: at.y + i * 40 } : null;
            if (canLink(it)) await addImagePath(it.path, insert, point);
            else if (it.file) await addImageFile(it.file, insert, point);
            else throw new Error('save the project first: figures are copied into its folder');
        }
        flashSaveIndicator(images.length > 1 ? `${images.length} images added ✓` : 'Image added ✓');
    } catch (err) {
        flashSaveIndicator(`Could not add the image: ${err.message}`);
    }
}
